// Strip TypeScript header to parse JSON cleanly
const headerMatch = raw.match(/^(import[\s\S]*?export\s+const\s+translationsData:\s*Record<string,\s*Translations>\s*=\s*)/);
if (!headerMatch) {
  console.error('Could not find header in translationsData.ts');
  process.exit(1);
}

const header = headerMatch[1];
const jsonContent = raw.slice(header.length).trim().replace(/;$/, '');
const data = JSON.parse(jsonContent);

let updatedCount = 0;
for (const [lang, updates] of Object.entries(translationsUpdates)) {
  if (!data[lang]) continue;
  for (const [dotPath, newVal] of Object.entries(updates)) {
    const parts = dotPath.split('.');
    let cur = data[lang];
    for (let i = 0; i < parts.length - 1; i++) {
      if (!cur[parts[i]]) cur[parts[i]] = {};
      cur = cur[parts[i]];
    }
    const lastKey = parts[parts.length - 1];
    cur[lastKey] = newVal;
    updatedCount++;
  }
}

console.log(`Updated ${updatedCount} field values across ${Object.keys(translationsUpdates).length} languages.`);

const output = `${header}${JSON.stringify(data, null, 2)};\n`;
fs.writeFileSync(filePath, output, 'utf8');
